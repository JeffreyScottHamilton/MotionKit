import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { registry } from "../registry";
import { SOURCES } from "./sources";

const root = resolve(__dirname, "..");

const provenance = registry.map((e) => ({
  id: e.id,
  name: e.name,
  source: e.source,
  dependencies: e.dependencies,
  files: e.files,
}));
writeFileSync(join(root, "provenance.json"), JSON.stringify(provenance, null, 2) + "\n");

const sections = SOURCES.map((s) => {
  const ids = registry.filter((e) => e.source.project === s.id).map((e) => e.id);
  const licenseText = readFileSync(join(root, "scripts", "licenses", s.licenseFile), "utf8").trimEnd();
  return [
    `## ${s.projectName}`,
    "",
    `- Used for: ${s.licenseFor}`,
    `- Copyright: ${s.copyright}`,
    `- Repository: ${s.repoUrl}`,
    `- Commit: ${s.commit}`,
    `- Components: ${ids.length > 0 ? ids.join(", ") : "none yet"}`,
    "",
    "```text",
    licenseText,
    "```",
    "",
  ].join("\n");
});

const notices = [
  "# Third-party notices",
  "",
  "MotionKit's own code is MIT licensed. The files under `registry/ui/` and the",
  "shadcn/ui primitives in `components/ui/` keep their upstream copyright and license.",
  "This file is generated by `npm run gen:provenance` from `registry/` and `scripts/licenses/`.",
  "",
  ...sections,
].join("\n");
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), notices);

console.log(`Wrote provenance.json (${provenance.length} entries) and THIRD_PARTY_NOTICES.md (${SOURCES.length} sources).`);
